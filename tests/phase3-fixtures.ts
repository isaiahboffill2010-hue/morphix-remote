export interface FakeCall {
  file: string;
  args: string[];
}

/**
 * Fake process runner standing in for PrusaSlicer/OrcaSlicer: answers --help with a
 * version banner and "slices" by writing fixture G-code where the real CLI would.
 */
export function fakeSlicerExec(gcode = PRUSA_GCODE, overrides: Partial<ExecResult> = {}): { exec: ExecFileFn; calls: FakeCall[] } {
  const calls: FakeCall[] = [];
  const exec: ExecFileFn = async (file, args, opts) => {
    calls.push({ file, args });
    if (args[0] === "--help") return { code: 0, stdout: "PrusaSlicer-2.9.0+linux-aarch64-GTK3 based on Slic3r\nUsage: ...", stderr: "", timedOut: false };
    if (overrides.code !== undefined && overrides.code !== 0) return { code: overrides.code, stdout: "", stderr: overrides.stderr ?? "boom", timedOut: false };
    const outIdx = args.indexOf("--output");
    if (outIdx >= 0) await writeFile(args[outIdx + 1], gcode);
    const dirIdx = args.indexOf("--outputdir");
    if (dirIdx >= 0) await writeFile(join(args[dirIdx + 1], "plate_1.gcode"), gcode);
    void opts;
    return { code: 0, stdout: "Slicing done", stderr: "", timedOut: false, ...overrides };
  };
  return { exec, calls };
}
