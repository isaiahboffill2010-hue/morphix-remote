/** Indexed axis-aligned box with outward winding. */
export function box(sx: number, sy: number, sz: number, o = { x: 0, y: 0, z: 0 }): Mesh {
  const v = [
    [0, 0, 0], [sx, 0, 0], [sx, sy, 0], [0, sy, 0],
    [0, 0, sz], [sx, 0, sz], [sx, sy, sz], [0, sy, sz],
  ].flatMap(([x, y, z]) => [x + o.x, y + o.y, z + o.z]);
  const f = [
    0, 2, 1, 0, 3, 2, // bottom (-Z)
    4, 5, 6, 4, 6, 7, // top (+Z)
    0, 1, 5, 0, 5, 4, // -Y
    1, 2, 6, 1, 6, 5, // +X
    2, 3, 7, 2, 7, 6, // +Y
    3, 0, 4, 3, 4, 7, // -X
  ];
  return { positions: Float32Array.from(v), indices: Uint32Array.from(f) };
}

/** Unwelded triangle soup of a mesh (like a freshly parsed STL). */
export function soup(m: Mesh): Mesh {
  const positions = new Float32Array(m.indices.length * 3);
  m.indices.forEach((vi, i) => positions.set(m.positions.subarray(vi * 3, vi * 3 + 3), i * 3));
  return { positions, indices: Uint32Array.from({ length: m.indices.length }, (_, i) => i) };
}

/** Square pyramid standing on its apex: 20x20 base at z=20 facing up, apex at (10,10,0). */
export function invertedPyramid(): Mesh {
  const positions = Float32Array.from([0, 0, 20, 20, 0, 20, 20, 20, 20, 0, 20, 20, 10, 10, 0]);
  const indices = Uint32Array.from([0, 1, 2, 0, 2, 3, 1, 0, 4, 2, 1, 4, 3, 2, 4, 0, 3, 4]);
  return { positions, indices };
}

